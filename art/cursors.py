S = 2  # screen px per art px
os.makedirs('public/cursors', exist_ok=True)
for name, (m, hot) in MAPS.items():
    rows = m.strip('\n').splitlines(); h, w = len(rows), len(rows[0])
    cells = {(x, y): c for y, r in enumerate(rows) for x, c in enumerate(r) if c != '.'}
    halo = {(x + dx, y + dy) for (x, y) in cells for dx in (-1, 0, 1) for dy in (-1, 0, 1)} - set(cells)
    rects = []
    for (x, y) in sorted(halo):
        rects.append(f'<rect x="{(x+1)*S}" y="{(y+1)*S}" width="{S}" height="{S}" fill="{WHITE}"/>')
    for (x, y), c in cells.items():
        rects.append(f'<rect x="{(x+1)*S}" y="{(y+1)*S}" width="{S}" height="{S}" fill="{NAVY if c == "O" else YEL}"/>')
    W, H = (w + 2) * S, (h + 2) * S
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" shape-rendering="crispEdges">{"".join(rects)}</svg>'
    open(f'public/cursors/{name}.svg', 'w').write(svg)
    print(name, W, H, 'hotspot', (hot[0] + 1) * S, (hot[1] + 1) * S)
